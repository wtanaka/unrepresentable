#!/bin/sh
# Consumer CI entry point for unrepresentable @VERSION@.
#
# This file is a TEMPLATE. A release process replaces the @...@ markers with
# the version and the sha256 of each release binary and publishes the result as
# the release asset `unrepresentable.sh`. Copy that asset into your repository
# (for example as ci/unrepresentable.sh) and run it from CI after a full
# checkout (fetch-depth: 0 so `origin/main` exists).
#
# It downloads the pinned binary, verifies its sha256 and refuses on mismatch,
# runs `self-test`, then `check --against` the base branch, then `canaries`.
# It reads no override from the environment except GITHUB_BASE_REF (set by
# GitHub on pull requests; defaults to main). It does no arithmetic: hashes are
# compared as strings. Needs: curl or wget, git, and sha256sum or shasum.
set -eu

version='@VERSION@'
repo='wtanaka/unrepresentable'
sha_linux_x86_64='@SHA256_X86_64_UNKNOWN_LINUX_GNU@'
sha_linux_aarch64='@SHA256_AARCH64_UNKNOWN_LINUX_GNU@'
sha_macos_x86_64='@SHA256_X86_64_APPLE_DARWIN@'
sha_macos_aarch64='@SHA256_AARCH64_APPLE_DARWIN@'
sha_windows_x86_64='@SHA256_X86_64_PC_WINDOWS_MSVC@'

die() {
  printf 'unrepresentable.sh: %s\n' "$1" >&2
  exit 2
}

kernel="$(uname -s)"
machine="$(uname -m)"
case "$kernel/$machine" in
  Linux/x86_64) target='x86_64-unknown-linux-gnu'; want="$sha_linux_x86_64"; suffix='' ;;
  Linux/aarch64 | Linux/arm64) target='aarch64-unknown-linux-gnu'; want="$sha_linux_aarch64"; suffix='' ;;
  Darwin/x86_64) target='x86_64-apple-darwin'; want="$sha_macos_x86_64"; suffix='' ;;
  Darwin/arm64 | Darwin/aarch64) target='aarch64-apple-darwin'; want="$sha_macos_aarch64"; suffix='' ;;
  MINGW*/* | MSYS*/* | CYGWIN*/*) target='x86_64-pc-windows-msvc'; want="$sha_windows_x86_64"; suffix='.exe' ;;
  *) die "unsupported platform $kernel/$machine" ;;
esac

case "$want" in
  @*) die "this script was not generated by a release (hash placeholder left in place)" ;;
esac

command -v git >/dev/null 2>&1 || die "git is required"
if command -v curl >/dev/null 2>&1; then
  fetch() { curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 --output "$2" "$1"; }
elif command -v wget >/dev/null 2>&1; then
  fetch() { wget --quiet --https-only --output-document="$2" "$1"; }
else
  die "curl or wget is required"
fi
if command -v sha256sum >/dev/null 2>&1; then
  hash_of() { sha256sum "$1" | cut -d ' ' -f 1; }
elif command -v shasum >/dev/null 2>&1; then
  hash_of() { shasum -a 256 "$1" | cut -d ' ' -f 1; }
else
  die "sha256sum or shasum is required"
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT HUP INT TERM
bin="$work/unrepresentable$suffix"

fetch "https://github.com/$repo/releases/download/v$version/unrepresentable-$target$suffix" "$bin"
got="$(hash_of "$bin")"
if [ "$got" != "$want" ]; then
  die "sha256 mismatch for unrepresentable-$target$suffix: expected $want, got $got; refusing to run it"
fi
chmod +x "$bin"

root="$(git rev-parse --show-toplevel)"
base_ref="origin/${GITHUB_BASE_REF:-main}"

"$bin" self-test "$root"
"$bin" check --against "$base_ref" "$root"
"$bin" canaries "$root"
