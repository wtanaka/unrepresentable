/// A manifest with the workspace lints and the given extra text.
fn manifest(name: &Name, extra: &Message) -> Message {
    Message::from_string(format!(
        "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[lints]\nworkspace = true\n\n{}",
        name.as_str(),
        extra.as_str()
    ))
}

/// A sandbox with `crates/core-lib` (library `lib_extra`) and `crates/app`, whose
/// `main.rs` matches on `core-lib`'s enum written through `use_line`, with a
/// catch-all arm.
fn app_over_core_lib(name: &Name, case: &AppCase) -> Result<Outcome, Fail> {
    let sandbox = Sandbox::create(name)?;
    let config = Message::from_string(format!(
        "{}\n[member.core-lib]\nrole = \"pure\"\n",
        Sandbox::default_config(&Name::of("app")).as_str()
    ));
    sandbox.seed_members(&[Name::of("app"), Name::of("core-lib")], &config)?;
    sandbox.write(&rel!("Cargo.lock"), &msg!(LOCK_APP_AND_CORE))?;
    sandbox.write(
        &rel!("crates/core-lib/Cargo.toml"),
        &manifest(&Name::of("core-lib"), &case.lib_extra),
    )?;
    sandbox.write(
        &rel!("crates/core-lib/src/lib.rs"),
        &msg!("pub enum Kind {\n    A,\n    B,\n}\n"),
    )?;
    sandbox.write(
        &rel!("crates/app/Cargo.toml"),
        &manifest(&Name::of("app"), &case.app_deps),
    )?;
    sandbox.write(
        &rel!("crates/app/src/main.rs"),
        &Message::from_string(format!(
            "{}\nfn main() {{}}\nfn f(kind: Kind) {{\n    match kind {{\n        Kind::A => (),\n        _ => (),\n    }}\n}}\n",
            case.use_line.as_str()
        )),
    )?;
    run_committed(&sandbox)
}

