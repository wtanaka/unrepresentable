/// What differs between the `app` + `core-lib` workspaces below.
struct AppCase {
    /// The `[dependencies]` text of `app`'s manifest.
    app_deps: Message,
    /// Extra text of `core-lib`'s manifest, such as a `[lib]` table.
    lib_extra: Message,
    /// The `use` line of `app`'s `main.rs` that names `core-lib`'s enum.
    use_line: Message,
}

/// Text placed around the default config: `top` in front of its tables, `tail` after.
struct Around {
    tail: Message,
    top: Message,
}

/// The config on `main` and the one that replaces it on `work`.
struct Step {
    after: Message,
    before: Message,
}

/// The `fx` package of a seeded sandbox, committed on `main` with `config`.
fn prepared(name: &Name, config: &Message) -> Result<Sandbox, Fail> {
    let package = Name::of("fx");
    let sandbox = Sandbox::create(name)?;
    sandbox.seed(&package, config)?;
    sandbox.write(&rel!("src/main.rs"), &msg!("fn main() {}\n"))?;
    Ok(sandbox)
}

/// Commits everything on `main` and runs against `HEAD`.
fn run_committed(sandbox: &Sandbox) -> Result<Outcome, Fail> {
    sandbox.init_repo()?;
    sandbox.run(&[Flag::Range(msg!("HEAD"))])
}

/// The default config with `around` added.
fn config_with(around: &Around) -> Message {
    let base = Sandbox::default_config(&Name::of("fx"));
    Message::from_string(format!(
        "{}{}{}",
        around.top.as_str(),
        base.as_str(),
        around.tail.as_str()
    ))
}

/// Commits `step.before` as the config on `main`, then `step.after` on `work`,
/// and runs against `main`.
fn config_edit(name: &Name, step: &Step) -> Result<Outcome, Fail> {
    let sandbox = prepared(name, &step.before)?;
    sandbox.init_repo()?;
    sandbox.git(&msg!("checkout -q -b work"))?;
    sandbox.write(&rel!(".unrepresentable/config"), &step.after)?;
    sandbox.commit_all(&Name::of("config"))?;
    sandbox.run(&[Flag::Against(Name::of("main"))])
}

#[test]
fn narrowing_a_ban_with_files_needs_approval() {
    assert_eq!(
        check_narrowing_a_ban_with_files_needs_approval(),
        Ok(()),
        "narrowing_a_ban_with_files_needs_approval"
    );
}

fn check_narrowing_a_ban_with_files_needs_approval() -> Result<(), Fail> {
    let wide = config_with(&around!(
        "",
        "\n[[ban]]\nid = \"no-writes\"\npaths = [\"std::fs::write\"]\n"
    ));
    let narrow = config_with(&around!(
        "",
        "\n[[ban]]\nid = \"no-writes\"\nfiles = [\"src/**\"]\npaths = [\"std::fs::write\"]\n"
    ));
    let outcome = config_edit(
        &Name::of("hard-ban-narrowed"),
        &Step {
            after: narrow,
            before: wide,
        },
    )?;
    ensure_eq!(
        outcome.exit,
        Exit::Approval,
        "a ban with no files applies everywhere; naming files narrows it"
    );
    ensure!(
        outcome.has_approval(&msg!("CONFIG_LOOSENED removed ban-files:no-writes:**"))
            == Answer::Yes,
        "the narrowing is named: {:?}",
        outcome.approvals()
    );
    Ok(())
}

