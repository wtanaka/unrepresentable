//! Cases found by a review of the tool: each one is a way a change, a config or
//! a manifest could make a check pass without the check having run.
use core::iter::once;

use crate::support::{Answer, Edit, Exit, Fail, Flag, Message, Name, Outcome, RelPath, Sandbox};

#[cfg(unix)]
use crate::support::Link;

macro_rules! msg {
    ($text:expr_2021) => {
        Message::of($text)
    };
}

macro_rules! rel {
    ($text:expr_2021) => {
        RelPath::of($text)
    };
}

macro_rules! around {
    ($top:expr_2021, $tail:expr_2021) => {
        Around {
            tail: msg!($tail),
            top: msg!($top),
        }
    };
}

