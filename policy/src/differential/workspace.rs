//! Making a complete temporary workspace for a differential input that has no
//! `.unrepresentable/config` of its own, or that came from a pull request.
//!
//! The corpus is scanned, not built. So the workspace never uses the input's
//! manifests or dependencies: every crate in the input becomes a member with a
//! generated manifest that has no dependencies, and a bare source tree becomes
//! one such member. That keeps `Cargo.lock` a fixed text that matches the
//! manifests without any network, and lets `cargo clippy` ask for the lint
//! tables without fetching anything. The workspace gets the config, the empty
//! ledgers and a git repository with one commit, so the range `HEAD` resolves
//! to a base that has no changes.
//!
//! An input from the pull request (`Origin::Head`) is never used as it is, even
//! with a config of its own. Its configuration, manifests and build scripts are
//! the way a pull request would run code in whatever evaluates it (`.cargo`
//! with a `rustc-wrapper`, `rust-toolchain*` with a path toolchain, a
//! `build.rs`, a `Cargo.toml` with a `build` key), so the workspace is always
//! generated, and `.cargo`, `.unrepresentable`, `build.rs`, `rust-toolchain*`
//! and `Cargo.*` are removed from the copy. The sandbox the binaries run in is
//! the second line of defence.

use super::Origin;
use crate::failure::Failure;
use crate::io::{self, CopyPlan, EntryKind};
use crate::process;
use crate::types::{Answer, Count, Holds as _, Message, Name, Text};
use std::path::{Path, PathBuf};

/// The empty canary exemptions table.
const CANARY_EXEMPTIONS: &str = "# Canary exemptions\n\n## Canary exemptions\n\n| Lint | Why it cannot be triggered |\n| --- | --- |\n| \u{2014} | \u{2014} |\n";
/// The directory the crates of an input are copied under.
const CRATES_DIR: &str = "crates";
/// The start of the config: a forbidden baseline, an explicit `default-range` and
/// `code`. Without a range the base binary exits 2 ("no change range") before it
/// reports anything. `HEAD` names no change at all, so the comparison is about
/// the scan findings only. `code` is required by the tool (a config without it
/// exits 2); every member lives under `crates/`.
const CONFIG_HEAD: &str =
    "baseline = \"forbidden\"\ndefault-range = \"HEAD\"\ncode = [\"crates/**\"]\n";
/// The empty ledger.
const LEDGER: &str = "# .unrepresentable/ledger.md\n\n## Expect ledger\n\n| File | Item | Lint | Reason |\n| --- | --- | --- | --- |\n| \u{2014} | \u{2014} | \u{2014} | \u{2014} |\n\n## Lint omissions\n\n| Lint | Contradicts | Reason |\n| --- | --- | --- |\n| \u{2014} | \u{2014} | \u{2014} |\n";
/// The lock file header cargo writes.
const LOCK_HEAD: &str =
    "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n";
/// The name of the member that holds a bare source tree.
const TREE_MEMBER: &str = "corpus";
/// The directory, under the member's `src`, that holds a bare source tree.
const TREE_DIR: &str = "tree";

/// An input directory and the temporary workspace made for it.
struct Made {
    /// Where the input came from.
    origin: Origin,
    /// The input directory.
    source: PathBuf,
    /// The workspace directory.
    workspace: PathBuf,
}

/// The workspace root for an input directory. A trusted input (public or
/// hidden) with its own `.unrepresentable/config` is used as it is. Any other
/// input, and every input from the pull request, gets a temporary workspace,
/// see the module documentation.
pub(crate) fn make_workspace(source: &Path, origin: Origin) -> Result<PathBuf, Failure> {
    let own_config = io::is_file(&source.join(".unrepresentable/config")) == Answer::Yes;
    if own_config && origin != Origin::Head {
        return Ok(source.to_path_buf());
    }
    let workspace = process::make_temp_dir()?;
    let made = Made {
        origin,
        source: source.to_path_buf(),
        workspace: workspace.clone(),
    };
    match populate(&made).and_then(|()| process::init_repository(&workspace)) {
        Ok(()) => Ok(workspace),
        Err(failure) => match io::remove_tree(&workspace) {
            Ok(()) | Err(_) => Err(failure),
        },
    }
}

/// The config for members that are all pure.
fn config_for(members: &[Name]) -> Text {
    let sections: Vec<String> = members
        .iter()
        .map(|member| format!("\n[member.{}]\nrole = \"pure\"\n", member.as_str()))
        .collect();
    Text::from_string(format!("{CONFIG_HEAD}{}", sections.concat()))
}

/// The directories under `dir` that hold a crate: a `Cargo.toml` and a
/// `src/lib.rs` or `src/main.rs`. The search does not go into a crate.
fn find_crates(dir: &Path, found: &mut Vec<PathBuf>) -> Result<(), Failure> {
    let has_source = io::is_file(&dir.join("src/lib.rs")) == Answer::Yes
        || io::is_file(&dir.join("src/main.rs")) == Answer::Yes;
    if io::is_file(&dir.join("Cargo.toml")) == Answer::Yes && has_source {
        found.push(dir.to_path_buf());
        return Ok(());
    }
    for entry in io::list_dir(dir)? {
        if entry.kind == EntryKind::Dir && !matches!(entry.name.as_str(), ".git" | "target") {
            find_crates(&dir.join(entry.name.as_str()), found)?;
        }
    }
    Ok(())
}

/// Whether `name` is a file or directory that makes cargo, rustup or the tool
/// read configuration, or run code, from the place it is in.
fn is_hazard(name: &Name) -> Answer {
    (matches!(
        name.as_str(),
        ".cargo" | ".unrepresentable" | "build.rs" | "rust-toolchain" | "rust-toolchain.toml"
    ) || name.as_str().starts_with("Cargo."))
    .answer()
}

/// The lock file for members that have no dependencies. `names` is sorted.
fn lock_for(names: &[Name]) -> Text {
    let packages: Vec<String> = names
        .iter()
        .map(|name| {
            format!(
                "\n[[package]]\nname = \"{}\"\nversion = \"0.0.0\"\n",
                name.as_str()
            )
        })
        .collect();
    Text::from_string(format!("{LOCK_HEAD}{}", packages.concat()))
}

/// The manifest of a member: no dependencies, nothing to fetch, and no build
/// script. Cargo runs a `build.rs` at the crate root even when the manifest
/// does not name it, and `cargo clippy` (which the tool runs for the lint
/// tables) builds and runs it first. A crate of the public corpus has one
/// (`proc-macro2`), and a pull request may add one, so `build = false` turns the
/// automatic detection off: no generated workspace can run a build script.
fn manifest_for(name: &Name) -> Text {
    Text::from_string(format!(
        "[package]\nname = \"{}\"\nversion = \"0.0.0\"\nedition = \"2021\"\nbuild = false\n",
        name.as_str()
    ))
}

/// Removes from the tree under `dir` every file and directory that
/// `is_hazard` names.
fn strip_hazards(dir: &Path) -> Result<(), Failure> {
    for entry in io::list_dir(dir)? {
        let path = dir.join(entry.name.as_str());
        match (is_hazard(&entry.name), entry.kind) {
            (Answer::Yes, EntryKind::Dir) => io::remove_tree(&path)?,
            (Answer::Yes, EntryKind::File | EntryKind::Other) => io::remove_file(&path)?,
            (Answer::No, EntryKind::Dir) => strip_hazards(&path)?,
            (Answer::No, EntryKind::File | EntryKind::Other) => {}
        }
    }
    Ok(())
}

/// Removes the hazards from a copy of an input that came from the pull request.
fn clean_copy(made: &Made, copy: &Path) -> Result<(), Failure> {
    match made.origin {
        Origin::Head => strip_hazards(copy),
        Origin::Hidden | Origin::Public => Ok(()),
    }
}

/// The name of the member for the crate with this index.
fn member_name(index: Count) -> Name {
    Name::from_string(format!("corpus-{:03}", index.get()))
}

/// Writes the files every workspace needs and the members of the input.
fn populate(made: &Made) -> Result<(), Failure> {
    let workspace = made.workspace.as_path();
    let mut crates = Vec::new();
    find_crates(&made.source, &mut crates)?;
    let members = if crates.is_empty() {
        write_tree(made)?
    } else {
        write_crates(made, &crates)?
    };
    io::write_text(&workspace.join("Cargo.lock"), &lock_for(&members))?;
    io::create_dirs(&workspace.join(".unrepresentable"))?;
    io::write_text(
        &workspace.join(".unrepresentable/config"),
        &config_for(&members),
    )?;
    io::write_text(
        &workspace.join(".unrepresentable/ledger.md"),
        &Text::of(LEDGER),
    )?;
    io::write_text(
        &workspace.join(".unrepresentable/canary-exemptions.md"),
        &Text::of(CANARY_EXEMPTIONS),
    )
}

/// The `.rs` files under `dir`, in name order.
fn rust_files(dir: &Path, found: &mut Vec<PathBuf>) -> Result<(), Failure> {
    for entry in io::list_dir(dir)? {
        let path = dir.join(entry.name.as_str());
        match entry.kind {
            EntryKind::Dir => rust_files(&path, found)?,
            EntryKind::File
                if Path::new(entry.name.as_str()).extension() == Some("rs".as_ref()) =>
            {
                found.push(path);
            }
            EntryKind::File | EntryKind::Other => {}
        }
    }
    Ok(())
}

/// Copies each crate of the input into its own member with a generated
/// manifest; returns the member names.
fn write_crates(made: &Made, crates: &[PathBuf]) -> Result<Vec<Name>, Failure> {
    let workspace = made.workspace.as_path();
    let mut names = Vec::new();
    for (index, source) in crates.iter().enumerate() {
        let name = member_name(Count::new(index));
        let dest = workspace.join(CRATES_DIR).join(name.as_str());
        io::copy_tree(&CopyPlan {
            from: source.clone(),
            to: dest.clone(),
        })?;
        clean_copy(made, &dest)?;
        io::write_text(&dest.join("Cargo.toml"), &manifest_for(&name))?;
        if io::is_file(&dest.join("Cargo.lock")) == Answer::Yes {
            io::remove_file(&dest.join("Cargo.lock"))?;
        }
        names.push(name);
    }
    io::write_text(
        &workspace.join("Cargo.toml"),
        &Text::from_string(format!(
            "[workspace]\nmembers = [\"{CRATES_DIR}/*\"]\nresolver = \"2\"\n"
        )),
    )?;
    Ok(names)
}

/// Copies a bare source tree under the `src` of one member and generates a
/// `src/lib.rs` that names every `.rs` file of the tree with `#[path]`, so
/// each file is reached and the rules scan it; returns the member name.
fn write_tree(made: &Made) -> Result<Vec<Name>, Failure> {
    let workspace = made.workspace.as_path();
    let name = Name::of(TREE_MEMBER);
    let tree = workspace.join("src").join(TREE_DIR);
    io::copy_tree(&CopyPlan {
        from: made.source.clone(),
        to: tree.clone(),
    })?;
    clean_copy(made, &tree)?;
    let mut files = Vec::new();
    rust_files(&tree, &mut files)?;
    let mut lib = Vec::new();
    for (index, file) in files.iter().enumerate() {
        match file.strip_prefix(&tree) {
            Ok(relative) => lib.push(format!(
                "#[path = \"{TREE_DIR}/{}\"]\nmod m{index:04};\n",
                relative.to_string_lossy()
            )),
            Err(_) => {
                return Err(Failure::internal(&Message::of(
                    "a source file is outside its own tree",
                )))
            }
        }
    }
    io::write_text(
        &workspace.join("src/lib.rs"),
        &Text::from_string(lib.concat()),
    )?;
    io::write_text(&workspace.join("Cargo.toml"), &manifest_for(&name))?;
    Ok(vec![name])
}
